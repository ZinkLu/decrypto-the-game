export function translate(locale: Locale, message: string, values: unknown[] = []): string {
    let source = locale === 'en' ? messages[message] ?? message : message;
    if (locale === 'en' && source === message && /^还需 \d+ 人$/.test(message)) source = message.replace(/^还需 (\d+) 人$/, 'NEED $1 MORE');
    return source.replace(/\{(\d+)\}/g, (token, index) => index in values ? String(values[index]) : token);
}
export function readLocale(): Locale {
    try { const saved = localStorage.getItem('decrypto-locale'); if (saved === 'en' || saved === 'zh') return saved; } catch { /* Storage may be disabled. */ }
    return typeof navigator !== 'undefined' && !navigator.language.toLowerCase().startsWith('zh') ? 'en' : 'zh';
}
export function saveLocale(locale: Locale) {
    try { localStorage.setItem('decrypto-locale', locale); } catch { /* Keep the selection for this session. */ }
}

/** Normalize protocol errors at the display boundary; room/game data stays intact. */
export function localizeError(locale: Locale, message: string): string {
    const protocol: Record<string, [string, string]> = {
        "already in a room": ["你已在房间中。", "You are already in a room."],
        "nickname must contain 1 to 20 characters": ["呼号需要 1–20 个字符。", "Use 1–20 characters for your call sign."],
        "room resume expired; please create or join a room": ["原房间已失效，请重新创建或加入。", "Your room has expired. Please create or join a room."],
        "not allowed to act in this phase": ["当前阶段由其他玩家操作。", "Another player acts in this phase."],
        "stale or already submitted action; sync and try again": ["此操作已提交或已过期，请等待阶段更新。", "This action was submitted or has expired. Wait for the next phase."],
        "provide three nonempty clues (80 characters max)": ["请填写三条线索，每条 1–80 个字符。", "Enter three clues, 1–80 characters each."],
        "provide exactly three clues": ["需要恰好三条线索。", "Exactly three clues are required."],
        "provide exactly three guesses": ["需要恰好三个数字。", "Exactly three digits are required."],
        "guess must contain three different digits from 1 to 4": ["请选择 1–4 中三个不重复的数字。", "Choose three different digits from 1 to 4."],
        "room capacity reached; try later": ["房间数量已满，请稍后重试。", "Room capacity reached. Please try later."],
        "room is full": ["这个房间已满。", "This room is full."],
        'only the room owner can add AI players': ['只有房主可以添加 AI。', 'Only the host can add AI players.'],
        'only the room owner can remove AI players': ['只有房主可以移除 AI。', 'Only the host can remove AI players.'],
        'not enough players to start (need at least 2 per team)': ['每队至少需要两位玩家。', 'Each team needs at least two players.'],
        'game session not found': ['对局已失效，请重新加入房间。', 'Game unavailable. Please rejoin the room.'],
    };
    const known = protocol[message];
    if (known) return known[locale === 'en' ? 1 : 0];
    const full = message.match(/^team ([AB]) is full \(max (\d+) players\)$/);
    if (full) return locale === 'en' ? `Team ${full[1]} is full (maximum ${full[2]} players).` : `${full[1]} 队已满，最多 ${full[2]} 人。`;
    if (/^(invalid |unknown message type:)/.test(message)) return locale === 'en' ? 'Invalid request. Please try again.' : '操作数据无效，请重试。';
    if (message.startsWith('failed to start game:')) return locale === 'en' ? 'Could not start the game. Please try again.' : '未能开始对局，请重试。';
    if (/^index \d+ out of range/.test(message)) return locale === 'en' ? 'That seat has changed. Please try again.' : '该席位已变化，请重试。';
    if (/^player at index .* is not an AI$/.test(message)) return locale === 'en' ? 'Only AI players can be removed here.' : '这里只能移除 AI 玩家。';
    return translate(locale, message);
}
